// Helper to get title from first two axes
export const CORE_NOUNS: Record<string, string> = {
  "00": "Architect",  // Legible + Sovereign
  "01": "Chorus",     // Legible + Symphonic
  "10": "Cipher",     // Illegible + Sovereign
  "11": "Weaver",     // Illegible + Symphonic
};

export const APOLLONIAN_MODIFIERS = ["Clear", "Ordered", "Balanced", "Still", "Bright"];
export const DIONYSIAN_MODIFIERS = ["Feral", "Drunk", "Dark", "Moonlit", "Wild"];

/**
 * Get a random modifier based on the Apollonian/Dionysian axis value
 * @param isDionysian - true if axis 7 is 1 (Dionysian), false if 0 (Apollonian)
 * @param seed - optional seed for deterministic selection
 */
export function getModifier(isDionysian: boolean, seed?: number): string {
  const modifiers = isDionysian ? DIONYSIAN_MODIFIERS : APOLLONIAN_MODIFIERS;
  const index = seed !== undefined
    ? Math.abs(seed) % modifiers.length
    : Math.floor(Math.random() * modifiers.length);
  return modifiers[index];
}

/**
 * Get the full archetype title from a binary key
 * @param binaryKey - 7-character binary string
 * @param modifierSeed - optional seed for deterministic modifier selection
 */
export function getArchetypeTitle(binaryKey: string, modifierSeed?: number): string {
  const nounKey = binaryKey.slice(0, 2);
  const isDionysian = binaryKey[6] === "1";
  const noun = CORE_NOUNS[nounKey];
  const modifier = getModifier(isDionysian, modifierSeed);
  return `The ${modifier} ${noun}`;
}

/**
 * Get epigram for a given binary key
 */
export function getEpigram(binaryKey: string): string | undefined {
  return EPIGRAMS[binaryKey];
}

/**
 * Axis order for binary key generation
 * MUST match the order used in EPIGRAMS keys
 */
export const BINARY_KEY_AXIS_ORDER = [
  "legible_illegible",
  "sovereign_symphonic",
  "anthro_xeno",
  "mortal_immortalist",
  "accel_steward",
  "aligned_autonomous",
  "apollonian_dionysian",
] as const;

export type AxisScores = Record<typeof BINARY_KEY_AXIS_ORDER[number], number>;

/**
 * Convert axis scores (0-16 scale) to a 7-bit binary key
 * Binarizes at midpoint: score >= 8 → "1" (high), score < 8 → "0" (low)
 */
export function scoresToBinaryKey(scores: AxisScores): string {
  return BINARY_KEY_AXIS_ORDER.map(axis => {
    const score = scores[axis] ?? 8;
    return score >= 8 ? "1" : "0";
  }).join("");
}

/**
 * Get the archetype image path for a given binary key
 */
export function getArchetypeImagePath(binaryKey: string): string {
  return `/archetypes/${binaryKey}.jpg`;
}

/**
 * Get complete archetype data from scores
 * Returns title, epigram, and image path
 */
export function getArchetypeFromScores(scores: AxisScores): {
  binaryKey: string;
  title: string;
  epigram: string;
  imagePath: string;
} {
  const binaryKey = scoresToBinaryKey(scores);
  const seed = parseInt(binaryKey, 2); // Deterministic modifier from key
  return {
    binaryKey,
    title: getArchetypeTitle(binaryKey, seed),
    epigram: getEpigram(binaryKey) ?? "The oracle is silent.",
    imagePath: getArchetypeImagePath(binaryKey),
  };
}
